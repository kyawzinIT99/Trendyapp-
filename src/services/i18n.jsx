const LanguageContext = createContext(null);

function interpolate(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (
    vars[key] == null ? `{${key}}` : String(vars[key])
  ));
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      return saved === 'my' ? 'my' : 'en';
    } catch {
      return 'en';
    }
  });

  const setLang = useCallback((next) => {
    const resolved = next === 'my' ? 'my' : 'en';
    setLangState(resolved);
    try { localStorage.setItem(LANG_KEY, resolved); } catch { /* ignore */ }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === 'my' ? 'my' : 'en';
    document.documentElement.dataset.lang = lang;
  }, [lang]);

  const t = useCallback((key, vars) => {
    const table = STRINGS[lang] || STRINGS.en;
    const raw = table[key] || STRINGS.en[key] || key;
    return vars ? interpolate(raw, vars) : raw;
  }, [lang]);

  const money = useCallback((amount) => formatMmk(amount, lang), [lang]);

  const value = useMemo(() => ({ lang, setLang, t, money }), [lang, setLang, t, money]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: 'en',
      setLang: () => {},
      t: (key, vars) => interpolate(STRINGS.en[key] || key, vars),
      money: (amount) => formatMmk(amount, 'en'),
    };
  }
  return ctx;
}

export function translateSheetStatus(t, label) {
  const key = TRACK_LABEL_TO_KEY[label];
  return key ? t(key) : label;
}

